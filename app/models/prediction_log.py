"""
app/models/prediction_log.py
Stores each prediction generated by the scoring engine so we can
later compare against the actual outcome and compute accuracy.
"""

import uuid
from datetime import datetime, timezone

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, Index, String, Text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base


class PredictionLog(Base):
    """
    A single prediction generated by the engine for an upcoming release.
    Links back to the EconomicRelease it was generated for.
    """

    __tablename__ = "prediction_logs"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    release_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("economic_releases.id", ondelete="CASCADE"),
        nullable=False,
    )
    signal: Mapped[str] = mapped_column(
        String(10), nullable=False
    )  # BUY | SELL | NEUTRAL
    signal_label: Mapped[str] = mapped_column(String(50), nullable=False)
    signal_subtitle: Mapped[str | None] = mapped_column(Text, nullable=True)
    confidence_score: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    composite_score: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    engine_metadata: Mapped[dict | None] = mapped_column(JSONB, nullable=True)
    is_correct: Mapped[bool | None] = mapped_column(Boolean, nullable=True)
    predicted_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc)
    )
    accuracy_checked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # Relationship back to release
    release: Mapped["EconomicRelease"] = relationship(  # noqa: F821
        back_populates="predictions"
    )

    __table_args__ = (
        Index("idx_predictions_release", "release_id"),
        Index("idx_predictions_signal", "signal"),
    )

    def __repr__(self) -> str:
        return f"<PredictionLog {self.signal} score={self.composite_score}>"
